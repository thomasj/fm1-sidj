// Generates sid/sid_tables.c for the SiDJ SID engine from reSID 0.16
// (third_party/resid-0.16, Copyright (C) 2004 Dag Lem):
//   - the eight combined-waveform sample tables (wave*.dat, 4096 bytes each)
//   - the filter cutoff tables, already converted to w0 as Filter::set_w0() does
//   - the 1024/Q table as Filter::set_Q() does
// Build and run with tools/gen_sid_tables.sh.
#include "filter.h"
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

struct FilterDump : public Filter {
    void dump_w0(FILE* out, const char* name, sound_sample* f0) {
        const double pi = 3.1415926535897932385;
        fprintf(out, "const uint32_t %s[2048] = {", name);
        for (int i = 0; i < 2048; i++) {
            sound_sample w0 = static_cast<sound_sample>(2 * pi * f0[i] * 1.048576);
            fprintf(out, "%s%d,", (i % 16) ? "" : "\n    ", w0);
        }
        fprintf(out, "\n};\n\n");
    }
    void run(FILE* out) {
        dump_w0(out, "sid_w0_6581", f0_6581);
        dump_w0(out, "sid_w0_8580", f0_8580);
    }
};

static void dump_wave(FILE* out, const char* dir, const char* model, const char* combo) {
    char path[512];
    snprintf(path, sizeof path, "%s/wave%s_%s.dat", dir, model, combo);
    FILE* f = fopen(path, "rb");
    if (!f) { perror(path); exit(1); }
    unsigned char buf[4096];
    if (fread(buf, 1, 4096, f) != 4096) { fprintf(stderr, "%s: short read\n", path); exit(1); }
    fclose(f);
    fprintf(out, "const uint8_t sid_wave%s_%s[4096] = {", model, combo);
    for (int i = 0; i < 4096; i++)
        fprintf(out, "%s0x%02x,", (i % 16) ? "" : "\n    ", buf[i]);
    fprintf(out, "\n};\n\n");
}

int main(int argc, char** argv) {
    if (argc != 3) { fprintf(stderr, "usage: gen_sid_tables RESID_DIR OUT.c\n"); return 1; }
    FILE* out = fopen(argv[2], "w");
    if (!out) { perror(argv[2]); return 1; }
    fprintf(out,
        "/* SPDX-License-Identifier: GPL-2.0-or-later */\n"
        "/* Generated by tools/gen_sid_tables.sh from reSID 0.16 (Copyright (C) 2004 Dag Lem).\n"
        " * Do not edit: combined-waveform samples, filter cutoff (w0) and 1024/Q tables. */\n"
        "#include \"sid_tables.h\"\n\n");
    const char* combos[] = { "_ST", "P_T", "PS_", "PST" };
    for (int m = 0; m < 2; m++)
        for (int c = 0; c < 4; c++)
            dump_wave(out, argv[1], m ? "8580" : "6581", combos[c]);
    FilterDump fd;
    fd.run(out);
    fprintf(out, "const uint16_t sid_1024_div_q[16] = {");
    for (int res = 0; res < 16; res++)
        fprintf(out, "%s%d,", res ? " " : " ", static_cast<int>(1024.0 / (0.707 + 1.0 * res / 0x0f)));
    fprintf(out, " };\n");
    fclose(out);
    return 0;
}
